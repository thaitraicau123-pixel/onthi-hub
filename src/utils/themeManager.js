export const THEME_STORAGE_KEY = 'onthi_selected_theme_v2';
export const WEATHER_STORAGE_KEY = 'onthi_weather_enabled_v1';
export const SLEEP_MODE_STORAGE_KEY = 'onthi_sleep_mode_pref_v1';

export function isWeatherEffectsEnabled() {
  try {
    const val = localStorage.getItem(WEATHER_STORAGE_KEY);
    return val !== 'false';
  } catch (e) {
    return true;
  }
}

export function setWeatherEffectsEnabled(enabled) {
  try {
    localStorage.setItem(WEATHER_STORAGE_KEY, enabled ? 'true' : 'false');
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('onthi-weather-toggle', { detail: enabled }));
    }
  } catch (e) {}
}

export function subscribeToWeatherToggle(callback) {
  if (typeof window === 'undefined') return () => {};
  const handler = (e) => callback(e.detail);
  window.addEventListener('onthi-weather-toggle', handler);
  return () => window.removeEventListener('onthi-weather-toggle', handler);
}

// =========================================================================
// CHẾ ĐỘ NGỦ (SLEEP / DARK MODE) & CHẾ ĐỘ BAN NGÀY (LIGHT / DAY MODE)
// Chỉ 5 chủ đề pastel/nhẹ nhàng được chạy Ban Ngày; toàn bộ 11 chủ đề 4K
// và rạp chiếu phim luôn luôn chạy Chế Độ Ngủ để đảm bảo màu sắc ăn khớp và tương phản cao nhất.
// =========================================================================

export const DAY_THEMES = [
  'bui-thai-cream',    // Bùi Thái Studio Warm Cream #fbf9f5
  'default',           // Notion Tối Giản
  'sakura-blossom',    // Mùa Hoa Anh Đào
  'botanical-garden',  // Khu Vườn Bơ Xanh
  'lofi-cafe',         // Cà Phê & Lofi
  'lemon-citrus'       // Nước Chanh Tươi Mát
];

export function isDayTheme(themeId) {
  return DAY_THEMES.includes(themeId);
}

export function getSleepMode(themeId) {
  const current = themeId ? THEMES.find(t => t.id === themeId) : getSelectedTheme();
  // Tất cả 11 chủ đề 4K / cinema / lễ hội BẮT BUỘC luôn luôn chạy Chế Độ Ngủ
  if (!current || !isDayTheme(current.id)) {
    return 'dark';
  }

  // Chỉ 5 chủ đề ban ngày mới kiểm tra thiết lập hoặc mặc định là 'light'
  try {
    const saved = localStorage.getItem(SLEEP_MODE_STORAGE_KEY);
    if (saved === 'dark' || saved === 'light') {
      return saved;
    }
  } catch (e) {}
  return 'light';
}

export function setSleepMode(mode) {
  const current = getSelectedTheme();
  // Nếu đang ở chủ đề 4K cinema, cưỡng chế giữ 'dark' để không bị chìm chữ và lệch màu
  let normalized = mode === 'dark' ? 'dark' : 'light';
  if (!isDayTheme(current.id)) {
    normalized = 'dark';
  }

  try {
    localStorage.setItem(SLEEP_MODE_STORAGE_KEY, normalized);
  } catch (e) {}

  if (typeof document !== 'undefined') {
    const root = document.documentElement;
    root.setAttribute('data-sleep-mode', normalized);
    root.classList.toggle('dark', normalized === 'dark');
    window.dispatchEvent(new CustomEvent('onthi-sleep-mode-change', { detail: normalized }));
  }

  return normalized;
}

export function toggleSleepMode() {
  const current = getSelectedTheme();
  if (!isDayTheme(current.id)) {
    // Không thể chuyển sang ban ngày với các theme 4K rạp chiếu phim
    return 'dark';
  }
  const currentMode = getSleepMode();
  const next = currentMode === 'dark' ? 'light' : 'dark';
  return setSleepMode(next);
}

export function subscribeToSleepMode(callback) {
  if (typeof window === 'undefined') return () => {};
  const handler = (e) => callback(e.detail || getSleepMode());
  window.addEventListener('onthi-sleep-mode-change', handler);
  return () => window.removeEventListener('onthi-sleep-mode-change', handler);
}

export function getSelectedThemeId() {
  try {
    const saved = localStorage.getItem(THEME_STORAGE_KEY);
    // If the saved theme was the old mario default, migrate to bui-thai-cream
    if (saved && saved !== 'super-mario-3d' && THEMES.some(t => t.id === saved)) {
      return saved;
    }
  } catch (e) {}
  return 'bui-thai-cream'; // Signature Bùi Thái Studio Warm Cream #fbf9f5
}

export function getSelectedTheme() {
  const id = getSelectedThemeId();
  return THEMES.find(t => t.id === id) || THEMES[0];
}

export function applyTheme(themeId) {
  const theme = THEMES.find(t => t.id === themeId) || THEMES[0];
  try {
    localStorage.setItem(THEME_STORAGE_KEY, theme.id);
  } catch (e) {}

  // Chỉ 5 chủ đề Ban Ngày mới chạy 'light'; các chủ đề 4K/Cinema tự động kích hoạt 'dark'
  let currentSleepMode = 'dark';
  if (isDayTheme(theme.id)) {
    try {
      const savedPref = localStorage.getItem(SLEEP_MODE_STORAGE_KEY);
      currentSleepMode = savedPref === 'dark' ? 'dark' : 'light';
    } catch (e) {
      currentSleepMode = 'light';
    }
  } else {
    currentSleepMode = 'dark';
  }

  // Set CSS Variables & Attributes on document element
  if (typeof document !== 'undefined') {
    const root = document.documentElement;
    root.setAttribute('data-theme', theme.id);
    root.setAttribute('data-sleep-mode', currentSleepMode);
    root.classList.toggle('dark', currentSleepMode === 'dark');
    root.style.setProperty('--theme-primary', theme.primaryColor);
    root.style.setProperty('--theme-primary-hover', theme.primaryHover);
    root.style.setProperty('--theme-border', theme.borderClass);

    // Update meta theme-color for mobile chrome & safari
    const metaThemeColor = document.querySelector('meta[name="theme-color"]');
    if (metaThemeColor) {
      metaThemeColor.setAttribute('content', theme.primaryColor);
    }

    // Dispatch global custom event for instant component reactivity
    window.dispatchEvent(new CustomEvent('onthi-theme-change', { detail: theme }));
    window.dispatchEvent(new CustomEvent('onthi-sleep-mode-change', { detail: currentSleepMode }));
  }

  return theme;
}

export function subscribeToTheme(callback) {
  if (typeof window === 'undefined') return () => {};

  const handler = (e) => {
    callback(e.detail || getSelectedTheme());
  };

  window.addEventListener('onthi-theme-change', handler);
  return () => window.removeEventListener('onthi-theme-change', handler);
}

